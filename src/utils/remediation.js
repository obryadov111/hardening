/**
 * Сроки и обязательность устранения нарушений по уровню критичности.
 *
 * Источники:
 *  - «Методика анализа защищённости ИС», ФСТЭК России, 25.11.2025, п. 3.4.4: уязвимости
 *    критического и высокого уровня заказчик устраняет обязательно; средний и низкий уровень —
 *    после экспертной оценки возможности эксплуатации (п. 3.4.5);
 *  - «Методика оценки уровня критичности уязвимостей программных, программно-аппаратных средств»,
 *    ФСТЭК России, 30.06.2025: сроки устранения по уровням.
 *
 * Оговорка: уровень берётся из пака (экспертная оценка автора пака), а не рассчитывается по
 * формуле V методики, поэтому сроки здесь — ориентир, а не результат расчёта по методике.
 * Подробно — README паков, раздел «Критичность (severity) и методики ФСТЭК».
 */
export const REMEDIATION_BY_SEVERITY = {
  critical: { deadline: "до 24 часов", mandatory: true, order: 0 },
  high: { deadline: "до 7 дней", mandatory: true, order: 1 },
  medium: { deadline: "до 4 недель", mandatory: false, order: 2 },
  low: { deadline: "до 4 месяцев", mandatory: false, order: 3 },
};

export const REMEDIATION_SOURCE_NOTE =
  "Сроки — ориентир по методике оценки уровня критичности уязвимостей ФСТЭК от 30.06.2025; " +
  "«обязательно» — п. 3.4.4 методики анализа защищённости от 25.11.2025. Уровень — оценка пака, " +
  "а не рассчитанный по методике показатель V.";

/** Сведения об устранении для результата проверки; null — устранять нечего (не fail) или уровень неизвестен. */
export function getRemediation(status, severity) {
  if (status !== "fail") return null;
  return REMEDIATION_BY_SEVERITY[(severity || "").toLowerCase()] || null;
}
